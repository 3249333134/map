const { test } = require('node:test')
const assert = require('node:assert/strict')
const { stops, clamp, snap, isCollapsed, LAYOUT } = require('../utils/panel')
test('收起高度紧凑固定，展开比例与拖动边界正确', () => {
  assert.deepEqual(stops(800), [84, 440])
  assert.deepEqual(stops(600), [84, 330])
  assert.equal(clamp(20, 84, 440), 84)
  assert.equal(clamp(900, 84, 440), 440)
})
test('显隐采用双阈值，轻微往返不让标题跳动', () => {
  assert.equal(isCollapsed(85, 84, true, true), true)
  assert.equal(isCollapsed(100, 84, true, true), false)
  assert.equal(isCollapsed(94, 84, false, true), false)
  assert.equal(isCollapsed(92, 84, false, true), true)
  assert.equal(isCollapsed(84, 84, false, false), true)
  assert.equal(LAYOUT.compact, 84)
})
test('松手吸附最近档位，快速滑动向对应方向切换', () => {
  const targets = stops(800)
  assert.equal(snap(380, 0, targets), 440)
  assert.equal(snap(440, 0.6, targets), 440)
  assert.equal(snap(430, -0.6, targets), 84)
  assert.equal(snap(84, -1, targets), 84)
})
test('慢速短拖也切换相邻档，轻触抖动不切换', () => {
  const targets = stops(800)
  assert.equal(snap(124, 0, targets, 84), 440)
  assert.equal(snap(400, 0, targets, 440), 84)
  assert.equal(snap(94, 0, targets, 84), 84)
  assert.equal(snap(84, 0, targets, 84), 84)
})
