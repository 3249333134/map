const { test } = require('node:test')
const assert = require('node:assert/strict')
let definition
require('../config/cloud').demoMode = true
global.Page = page => { definition = page }
const defaultWindow = { windowHeight: 800, screenHeight: 850, safeArea: { bottom: 830 } }
global.wx = { getWindowInfo: () => defaultWindow, hideKeyboard: () => {} }
require('../pages/index/index')
function page() {
  const instance = { ...definition, data: structuredClone(definition.data) }
  instance.setData = (values, callback) => { Object.assign(instance.data, values); if (callback) callback() }
  instance.onLoad()
  return instance
}
test('页面初始化、搜索和分类组合筛选', () => {
  const instance = page()
  assert.equal(instance.data.panelHeight, 403)
  assert.equal(instance.data.bottomBarHeight, 68)
  assert.equal(instance.data.bottomBarHeight - instance.data.safeBottom, 48, '安全区只由外层容器加一次')
  assert.equal(instance.data.safeBottom, 20)
  instance.search({ detail: { value: '公园' } })
  assert.equal(instance.data.items.length, 2)
  instance.category({ currentTarget: { dataset: { category: '户外' } } })
  assert.equal(instance.data.items.length, 2)
  instance.search({ detail: { value: '不存在的地点' } })
  assert.equal(instance.data.items.length, 0)
})
