test('连续滚动后筛选总能回顶，不依赖 scrollTop 数据恰好变化', () => {
  const instance = page()
  const updates = []
  instance.setData = (values, callback) => { updates.push(values); Object.assign(instance.data, values); if (callback) callback() }
  for (const position of [300, 170]) {
    instance.scrolled({ detail: { scrollTop: position } })
    instance.filter()
    assert.ok(updates.some(update => update.scrollTop === position))
    assert.equal(instance.data.scrollTop, 0)
  }
})
