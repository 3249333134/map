test('连续拖动与切换列表不重新取景，打字期间不自动缩放，结束搜索才调整一次', async () => {
  const instance = page()
  const frames = []
  instance.map = { includePoints: frame => frames.push(frame) }
  instance.selectPoint(3)
  await new Promise(resolve => setTimeout(resolve, 280))
  assert.equal(frames.length, 1)
  instance.returnToBrowse()
  instance.togglePanel()
  instance.dragStart({ touches: [{ clientY: 700 }] })
  instance.dragMove({ touches: [{ clientY: 650 }] })
  instance.dragEnd()
  instance.searchFocus()
  instance.search({ detail: { value: '公' } })
  instance.search({ detail: { value: '公园' } })
  await new Promise(resolve => setTimeout(resolve, 280))
  assert.equal(frames.length, 1)
  instance.finishSearch()
  await new Promise(resolve => setTimeout(resolve, 280))
  assert.equal(frames.length, 2)
  assert.equal(instance.data.viewMode, 'browse')
  assert.equal(instance.data.collapsed, false)
  instance.onUnload()
})
