test('无安全区和小屏幕时，底栏与面板按可用高度计算', () => {
  try {
    wx.getWindowInfo = () => ({ windowHeight: 568, screenHeight: 568 })
    const instance = page()
    assert.equal(instance.data.safeBottom, 0)
    assert.equal(instance.data.bottomBarHeight, 48)
    assert.deepEqual(instance.targets, [84, 286])
    assert.equal(instance.data.panelHeight, 286)
    assert.equal(instance.targets[0], 84, '收起后容纳 28px 把手区、44px 搜索框和 12px 间距')
    instance.togglePanel()
    assert.equal(instance.data.panelHeight, 84)
    wx.getWindowInfo = () => defaultWindow
    instance.onResize()
    assert.equal(instance.data.collapsed, true)
    assert.equal(instance.data.panelHeight, 84)
  } finally { wx.getWindowInfo = () => defaultWindow }
})
test('收起后慢速上拖可展开，拖完不会被按钮的误触立即收起', () => {
  const instance = page()
  instance.togglePanel()
  instance.dragStart({ touches: [{ clientY: 700 }] })
  instance.dragMove({ touches: [{ clientY: 660 }] })
  instance.drag.lastTime = Date.now() - 101
  instance.dragEnd()
  assert.equal(instance.data.collapsed, false)
  assert.equal(instance.data.panelHeight, instance.targets[1])
  instance.togglePanel()
  assert.equal(instance.data.collapsed, false)
})
test('手指未松开时上拖就展示内容，下拖到最小高度才隐藏', () => {
  const instance = page()
  instance.togglePanel()
  instance.dragStart({ touches: [{ clientY: 700 }] })
  instance.dragMove({ touches: [{ clientY: 450 }] })
  assert.equal(instance.data.dragging, true)
  assert.equal(instance.data.panelHeight, 334)
  assert.equal(instance.data.collapsed, false, '面板已拉高时不能继续隐藏标题、分类和列表')
  assert.ok(instance.data.items.length > 0)
  instance.dragMove({ touches: [{ clientY: 690 }] })
  assert.equal(instance.data.collapsed, false, '尚未回到最小高度时保留内容')
  instance.dragMove({ touches: [{ clientY: 700 }] })
  assert.equal(instance.data.panelHeight, 84)
  assert.equal(instance.data.collapsed, true)
  instance.dragCancel()
})
test('下拖收起后再次上拖，连续往返正常', () => {
  const instance = page()
  for (let count = 0; count < 3; count++) {
    instance.dragStart({ touches: [{ clientY: 400 }] })
    instance.dragMove({ touches: [{ clientY: 440 }] })
    instance.drag.lastTime = Date.now() - 101
    instance.dragEnd()
    assert.equal(instance.data.collapsed, true)
    assert.equal(instance.data.panelHeight, 84)
    instance.dragStart({ touches: [{ clientY: 700 }] })
    instance.dragMove({ touches: [{ clientY: 660 }] })
    instance.drag.lastTime = Date.now() - 101
    instance.dragEnd()
    assert.equal(instance.data.panelHeight, instance.targets[1])
  }
})
