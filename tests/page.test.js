test('确认搜索会展开结果；清空和无结果恢复入口都能恢复示例', () => {
  const instance = page()
  instance.togglePanel()
  instance.searchFocus()
  instance.keyboardChanged({ detail: { height: 300 } })
  instance.search({ detail: { value: '公园' } })
  instance.confirmSearch()
  assert.equal(instance.data.panelHeight, 403)
  assert.equal(instance.data.items.length, 2)
  assert.deepEqual(instance.data.markers.map(marker => marker.id), instance.data.items.map(item => item.id))
  instance.clearSearch()
  assert.equal(instance.data.items.length, 6)
  instance.search({ detail: { value: '不存在' } })
  assert.deepEqual(instance.data.markers, [])
  instance.resetFilters()
  assert.equal(instance.data.items.length, 6)
  assert.equal(instance.data.query, '')
})
